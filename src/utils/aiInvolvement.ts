// Ordered from least to most AI involvement.
export const aiInvolvementLevels = {
  'human-written': {
    label: 'Human-written',
    description: 'Written entirely by me. No AI was used for the text.',
  },
  'ai-polished': {
    label: 'AI-polished',
    description:
      'Written by me. AI was used to check and correct grammar, wording, and clarity.',
  },
  'ai-assisted': {
    label: 'AI-assisted',
    description:
      'I wrote and directed the draft. AI expanded some parts, which I edited heavily.',
  },
  'ai-summarized': {
    label: 'AI-summarized',
    description:
      'AI condensed or assembled from human-written material into this document. I reviewed the result.',
  },
  'ai-generated-reviewed': {
    label: 'AI-generated, reviewed',
    description: 'Mostly generated by AI. I checked it for accuracy.',
  },
  'ai-generated': {
    label: 'AI-generated',
    description: 'Generated by AI with little or no review by me.',
  },
} as const;

export type AiInvolvement = keyof typeof aiInvolvementLevels;

export function getAiInvolvement(value: unknown): AiInvolvement | undefined {
  if (value === undefined) {
    return undefined;
  }
  if (typeof value === 'string' && Object.hasOwn(aiInvolvementLevels, value)) {
    return value as AiInvolvement;
  }
  throw new Error(
    `Invalid ai_involvement ${JSON.stringify(value)}. Expected one of: ${Object.keys(aiInvolvementLevels).join(', ')}.`,
  );
}
